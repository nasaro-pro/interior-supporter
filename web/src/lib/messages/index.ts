/** 알 수 없는 키가 들어와도 화면이 깨지지 않게 한다. */
export function labelOf(
  map: Readonly<Record<string, string>>,
  key: string | null | undefined,
): string {
  if (!key) return "-";
  return map[key] ?? key;
}
